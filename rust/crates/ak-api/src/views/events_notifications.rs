//! `authentik.events.api.notifications.NotificationViewSet`: `list` and
//! `retrieve`.
//!
//! A `GenericViewSet` with the list/retrieve/update/destroy mixins on the
//! default backends; `owner_field = "user"`. It sets no `ordering`, so
//! pages come in whatever order `PostgreSQL` returns Django's query (the
//! text below is Django's). `event` is `EventSerializer` on
//! `notification.event`, fetched per row.

use ak_rbac::{Access, Model, Object, PkCast};
use serde::Serialize;
use sqlx::Row as _;
use uuid::Uuid;

use crate::{
    Answer, Decline,
    drf::{self, ApiRequest, Context, User},
    filters::{self, Field, Kind},
    pagination::{Page, page_size},
    py::{QueryDict, UuidLookup, uuid_lookup},
    sql::{Bind, DjangoQuery},
    views::{
        common::{ordering, search_terms},
        events_events::{self, EventData},
    },
};

const ALLOW_LIST: &str = "GET, HEAD, OPTIONS";
pub(crate) const ALLOW_DETAIL: &str = "GET, PUT, PATCH, DELETE, HEAD, OPTIONS";

pub(crate) const MODEL: Model<'static> = Model {
    app_label: "authentik_events",
    model_name: "notification",
    ctype_app_label: "authentik_events",
    ctype_model: "notification",
    pk_cast: PkCast::Uuid,
    db_table: "authentik_events_notification",
    pk_column: "uuid",
};

macro_rules! col {
    ($c:literal) => {
        concat!("\"authentik_events_notification\".\"", $c, "\"")
    };
}

const FROM: &str = "\"authentik_events_notification\"";
pub(crate) const SELECT: &str = concat!(
    col!("uuid"),
    ", ",
    col!("severity"),
    ", ",
    col!("body"),
    ", ",
    col!("hyperlink"),
    ", ",
    col!("hyperlink_label"),
    ", ",
    col!("created"),
    ", ",
    col!("event_id"),
    ", ",
    col!("seen"),
    ", ",
    col!("user_id"),
);

/// `filterset_fields`, generated by DRF's `DjangoFilterBackend`.
const FILTERS: &[Field] = &[
    Field {
        name: "severity",
        kind: Kind::Choice {
            column: col!("severity"),
            choices: &["notice", "warning", "alert"],
        },
    },
    Field {
        name: "body",
        kind: Kind::Char {
            column: col!("body"),
        },
    },
    Field {
        name: "created",
        kind: Kind::Declined,
    },
    Field {
        name: "event",
        kind: Kind::ForeignKeyUuid {
            column: col!("event_id"),
            target: ("authentik_events_event", "event_uuid"),
        },
    },
    Field {
        name: "seen",
        kind: Kind::Boolean {
            column: col!("seen"),
        },
    },
    Field {
        name: "user",
        kind: Kind::ForeignKeyInt {
            column: col!("user_id"),
            target: ("authentik_core_user", "id"),
        },
    },
];

/// Readable sources (`event` orders by the foreign key column).
const ORDERING: &[(&str, &str)] = &[
    ("pk", col!("uuid")),
    ("severity", col!("severity")),
    ("body", col!("body")),
    ("hyperlink", col!("hyperlink")),
    ("hyperlink_label", col!("hyperlink_label")),
    ("created", col!("created")),
    ("event", col!("event_id")),
    ("seen", col!("seen")),
];

/// `NotificationSerializer`.
#[derive(Serialize)]
pub(crate) struct NotificationData {
    pk: String,
    severity: String,
    body: String,
    hyperlink: Option<String>,
    hyperlink_label: Option<String>,
    created: String,
    event: Option<EventData>,
    seen: bool,
}

fn db(_: sqlx::Error) -> Decline {
    Decline("database error")
}

pub(crate) async fn serialize(
    ctx: &Context<'_>,
    rows: &[sqlx::postgres::PgRow],
) -> Result<Vec<NotificationData>, Decline> {
    let mut out = Vec::with_capacity(rows.len());
    for row in rows {
        let event_id: Option<Uuid> = row.try_get(6).map_err(db)?;
        let event = match event_id {
            None => None,
            Some(id) => {
                let rows = sqlx::query(sqlx::AssertSqlSafe(format!(
                    "SELECT {} FROM \"authentik_events_event\" WHERE \
                     \"authentik_events_event\".\"event_uuid\" = $1 LIMIT 21",
                    events_events::SELECT
                )))
                .bind(id)
                .fetch_all(ctx.pool)
                .await
                .map_err(db)?;
                Some(events_events::event(
                    rows.first().ok_or(Decline("dangling event"))?,
                )?)
            }
        };
        let uuid: Uuid = row.try_get(0).map_err(db)?;
        let created: chrono::DateTime<chrono::Utc> = row.try_get(5).map_err(db)?;
        out.push(NotificationData {
            pk: uuid.to_string(),
            severity: row.try_get(1).map_err(db)?,
            body: row.try_get(2).map_err(db)?,
            hyperlink: row.try_get(3).map_err(db)?,
            hyperlink_label: row.try_get(4).map_err(db)?,
            created: drf::datetime(created),
            event,
            seen: row.try_get(7).map_err(db)?,
        });
    }
    Ok(out)
}

pub(crate) async fn filter_queryset(
    ctx: &Context<'_>,
    query: &QueryDict,
    user: &User,
    allow: &'static str,
) -> Result<Result<DjangoQuery, Answer>, Decline> {
    let mut qs = DjangoQuery::new(FROM, SELECT, &[]);
    // No `search_fields`: `SearchFilter` leaves the queryset alone, but its
    // NUL check on `?search=` still runs.
    if let Err(answer) = search_terms(query, allow) {
        return Ok(Err(answer));
    }
    match ak_rbac::object_filter(ctx.pool, user.subject(), &MODEL, true)
        .await
        .map_err(|_| Decline("object filter raised"))?
    {
        ak_rbac::ObjectFilter::All => {}
        ak_rbac::ObjectFilter::Owner if !user.is_authenticated() => {
            return Err(Decline("anonymous owner filter"));
        }
        ak_rbac::ObjectFilter::Owner => {
            let p = qs.bind(Bind::Int(user.subject().user_id));
            qs.filter(format!("{} = {p}", col!("user_id")));
        }
        ak_rbac::ObjectFilter::Visible { .. } => return Err(Decline("object filter")),
    }
    match filters::clean(ctx.pool, query, FILTERS).await? {
        Ok(form) => {
            form.apply(&mut qs);
        }
        Err(errors) => return Ok(Err(drf::field_errors(&errors, allow))),
    }
    Ok(Ok(qs))
}

/// `GET /api/v3/events/notifications/`.
pub async fn list(
    ctx: &Context<'_>,
    req: &ApiRequest<'_>,
    query: &QueryDict,
) -> Result<Answer, Decline> {
    let tenant = drf::tenant(ctx, req).await?;
    let user = match drf::authenticate(ctx, req, ALLOW_LIST).await? {
        Ok(user) => user,
        Err(answer) => return Ok(answer),
    };
    if !user.is_authenticated() {
        return Ok(drf::permission_denied(&user, ALLOW_LIST));
    }
    let qs = match filter_queryset(ctx, query, &user, ALLOW_LIST).await? {
        Ok(qs) => qs,
        Err(answer) => return Ok(answer),
    };
    let order = ordering(query, ORDERING, &[], &[])?;
    let size = page_size(query, &tenant)?;
    let count = qs.count(ctx.pool).await?;
    let Some(page) = Page::choose(query, size, count)? else {
        return Ok(drf::detail(404, "Invalid page.", ALLOW_LIST));
    };
    let rows = qs.fetch(ctx.pool, &order, Some(page.slice())).await?;
    let results = serialize(ctx, &rows).await?;
    Ok(drf::json(200, &page.response(results), ALLOW_LIST))
}

/// `GET /api/v3/events/notifications/{pk}/`.
pub async fn retrieve(
    ctx: &Context<'_>,
    req: &ApiRequest<'_>,
    query: &QueryDict,
    pk: &str,
) -> Result<Answer, Decline> {
    drf::tenant(ctx, req).await?;
    let user = match drf::authenticate(ctx, req, ALLOW_DETAIL).await? {
        Ok(user) => user,
        Err(answer) => return Ok(answer),
    };
    let mut qs = match filter_queryset(ctx, query, &user, ALLOW_DETAIL).await? {
        Ok(qs) => qs,
        Err(answer) => return Ok(answer),
    };
    let uuid = match uuid_lookup(pk).map_err(|_| Decline("pk syntax"))? {
        UuidLookup::Valid(uuid) => uuid,
        UuidLookup::Invalid => return Ok(drf::detail(404, "Not found.", ALLOW_DETAIL)),
    };
    let p = qs.bind(Bind::Uuid(uuid));
    qs.filter(format!("{} = {p}", col!("uuid")));
    let rows = qs.fetch(ctx.pool, &[], None).await?;
    let row = match rows.as_slice() {
        [] => {
            return Ok(drf::detail(
                404,
                "No Notification matches the given query.",
                ALLOW_DETAIL,
            ));
        }
        [row] => row,
        _ => return Err(Decline("multiple objects")),
    };
    let owner: i32 = row.try_get(8).map_err(db)?;
    let pk_text = uuid.to_string();
    let access = ak_rbac::has_object_permission(
        ctx.pool,
        user.subject(),
        "GET",
        &Object {
            model: MODEL,
            pk: &pk_text,
        },
        owner == user.subject().user_id,
    )
    .await
    .map_err(|_| Decline("object permission raised"))?;
    match access {
        Access::Allow => {
            let mut one = serialize(ctx, &rows).await?;
            Ok(drf::json(
                200,
                &one.pop().ok_or(Decline("database error"))?,
                ALLOW_DETAIL,
            ))
        }
        Access::NotFound => Ok(drf::detail(404, "Not found.", ALLOW_DETAIL)),
        Access::Deny => Ok(drf::permission_denied(&user, ALLOW_DETAIL)),
    }
}
