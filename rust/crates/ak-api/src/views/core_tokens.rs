//! `authentik.core.api.tokens.TokenViewSet`: `list` and `retrieve`.
//!
//! Default backends; `lookup_field = "identifier"` and
//! `owner_field = "user"` (without the global view permission a user sees
//! their own tokens, never a 403). `user_obj` is `UserSerializer` on
//! `token.user`, fetched per token and without prefetches.

use ak_rbac::{Access, Model, Object, PkCast};
use serde::Serialize;
use sqlx::Row as _;
use uuid::Uuid;

use crate::{
    Answer, Decline,
    drf::{self, ApiRequest, Context, User},
    filters::{self, Field, Kind},
    pagination::{Page, page_size},
    py::QueryDict,
    sql::{Bind, DjangoQuery},
    views::{
        common::{django_search, ordering, search_terms},
        core_users::{self, UserData},
    },
};

const ALLOW_LIST: &str = "GET, POST, HEAD, OPTIONS";
const ALLOW_DETAIL: &str = "GET, PUT, PATCH, DELETE, HEAD, OPTIONS";

const MODEL: Model<'static> = Model {
    app_label: "authentik_core",
    model_name: "token",
    ctype_app_label: "authentik_core",
    ctype_model: "token",
    pk_cast: PkCast::Uuid,
    db_table: "authentik_core_token",
    pk_column: "token_uuid",
};

macro_rules! col {
    ($c:literal) => {
        concat!("\"authentik_core_token\".\"", $c, "\"")
    };
}

const FROM: &str = "\"authentik_core_token\"";
const SELECT: &str = concat!(
    col!("managed"),
    ", ",
    col!("expires"),
    ", ",
    col!("expiring"),
    ", ",
    col!("token_uuid"),
    ", ",
    col!("identifier"),
    ", ",
    col!("key"),
    ", ",
    col!("intent"),
    ", ",
    col!("user_id"),
    ", ",
    col!("description"),
);

/// `user__…` lookups join the user once (a forward foreign key).
const JOIN_USER: &str = "INNER JOIN \"authentik_core_user\" ON (\"authentik_core_token\".\"user_id\" = \
                         \"authentik_core_user\".\"id\")";

/// `filterset_fields`, generated by DRF's `DjangoFilterBackend`.
const FILTERS: &[Field] = &[
    Field {
        name: "identifier",
        kind: Kind::Char {
            column: col!("identifier"),
        },
    },
    Field {
        name: "intent",
        kind: Kind::Choice {
            column: col!("intent"),
            choices: &["verification", "api", "recovery", "app_password"],
        },
    },
    Field {
        name: "user__username",
        kind: Kind::JoinedChar {
            join: JOIN_USER,
            column: "\"authentik_core_user\".\"username\"",
        },
    },
    Field {
        name: "description",
        kind: Kind::Char {
            column: col!("description"),
        },
    },
    Field {
        name: "expires",
        kind: Kind::Declined,
    },
    Field {
        name: "expiring",
        kind: Kind::Boolean {
            column: col!("expiring"),
        },
    },
    Field {
        name: "managed",
        kind: Kind::Char {
            column: col!("managed"),
        },
    },
];

const SEARCH: &[&str] = &[
    col!("identifier"),
    col!("intent"),
    "\"authentik_core_user\".\"username\"",
    col!("description"),
];

/// Readable sources (`user_obj` has source `user`, which is listed).
const ORDERING: &[(&str, &str)] = &[
    ("pk", col!("token_uuid")),
    ("managed", col!("managed")),
    ("identifier", col!("identifier")),
    ("intent", col!("intent")),
    ("user", col!("user_id")),
    ("description", col!("description")),
    ("expires", col!("expires")),
    ("expiring", col!("expiring")),
];
const DEFAULT_ORDERING: &[&str] = &[
    concat!(col!("identifier"), " ASC"),
    concat!(col!("expires"), " ASC"),
];

/// `TokenSerializer`.
#[derive(Serialize)]
struct TokenData {
    pk: String,
    managed: Option<String>,
    identifier: String,
    intent: String,
    user: i32,
    user_obj: UserData,
    description: String,
    expires: Option<String>,
    expiring: bool,
}

fn db(_: sqlx::Error) -> Decline {
    Decline("database error")
}

async fn serialize_tokens(
    ctx: &Context<'_>,
    tenant: &drf::Tenant,
    query: &QueryDict,
    rows: &[sqlx::postgres::PgRow],
) -> Result<Vec<TokenData>, Decline> {
    let mut out = Vec::with_capacity(rows.len());
    for row in rows {
        let user_id: i32 = row.try_get(7).map_err(db)?;
        // `token.user`: `User.objects.get(pk=…)`.
        let user_rows = sqlx::query(sqlx::AssertSqlSafe(format!(
            "SELECT {} FROM \"authentik_core_user\" WHERE \"authentik_core_user\".\"id\" = $1 LIMIT 21",
            core_users::SELECT
        )))
        .bind(user_id)
        .fetch_all(ctx.pool)
        .await
        .map_err(db)?;
        let mut users = core_users::serialize_users(ctx, tenant, query, &user_rows, false).await?;
        let user_obj = users.pop().ok_or(Decline("token without user"))?;
        let uuid: Uuid = row.try_get(3).map_err(db)?;
        let expires: Option<chrono::DateTime<chrono::Utc>> = row.try_get(1).map_err(db)?;
        out.push(TokenData {
            pk: uuid.to_string(),
            managed: row.try_get(0).map_err(db)?,
            identifier: row.try_get(4).map_err(db)?,
            intent: row.try_get(6).map_err(db)?,
            user: user_id,
            user_obj,
            description: row.try_get(8).map_err(db)?,
            expires: expires.map(drf::datetime),
            expiring: row.try_get(2).map_err(db)?,
        });
    }
    Ok(out)
}

async fn filter_queryset(
    ctx: &Context<'_>,
    query: &QueryDict,
    user: &User,
    allow: &'static str,
) -> Result<Result<DjangoQuery, Answer>, Decline> {
    let mut qs = DjangoQuery::new(FROM, SELECT, &[]);
    let terms = match search_terms(query, allow) {
        Ok(terms) => terms,
        Err(answer) => return Ok(Err(answer)),
    };
    if !terms.is_empty() {
        qs.join(JOIN_USER);
    }
    django_search(&mut qs, SEARCH, &terms);
    // `ObjectFilter` with `owner_field = "user"`.
    match ak_rbac::object_filter(ctx.pool, user.subject(), &MODEL, true)
        .await
        .map_err(|_| Decline("object filter raised"))?
    {
        ak_rbac::ObjectFilter::All => {}
        // `filter(user=AnonymousUser())` raises.
        ak_rbac::ObjectFilter::Owner if !user.is_authenticated() => {
            return Err(Decline("anonymous owner filter"));
        }
        ak_rbac::ObjectFilter::Owner => {
            let p = qs.bind(Bind::Int(user.subject().user_id));
            qs.filter(format!("{} = {p}", col!("user_id")));
        }
        ak_rbac::ObjectFilter::Visible { .. } => return Err(Decline("object filter")),
    }
    match filters::clean(ctx.pool, query, FILTERS).await? {
        Ok(form) => {
            form.apply(&mut qs);
        }
        Err(errors) => return Ok(Err(drf::field_errors(&errors, allow))),
    }
    Ok(Ok(qs))
}

/// `GET /api/v3/core/tokens/`.
pub async fn list(
    ctx: &Context<'_>,
    req: &ApiRequest<'_>,
    query: &QueryDict,
) -> Result<Answer, Decline> {
    let tenant = drf::tenant(ctx, req).await?;
    let user = match drf::authenticate(ctx, req, ALLOW_LIST).await? {
        Ok(user) => user,
        Err(answer) => return Ok(answer),
    };
    if !user.is_authenticated() {
        return Ok(drf::permission_denied(&user, ALLOW_LIST));
    }
    let qs = match filter_queryset(ctx, query, &user, ALLOW_LIST).await? {
        Ok(qs) => qs,
        Err(answer) => return Ok(answer),
    };
    let order = ordering(query, ORDERING, &[], DEFAULT_ORDERING)?;
    let size = page_size(query, &tenant)?;
    let count = qs.count(ctx.pool).await?;
    let Some(page) = Page::choose(query, size, count)? else {
        return Ok(drf::detail(404, "Invalid page.", ALLOW_LIST));
    };
    let rows = qs.fetch(ctx.pool, &order, Some(page.slice())).await?;
    let results = serialize_tokens(ctx, &tenant, query, &rows).await?;
    Ok(drf::json(200, &page.response(results), ALLOW_LIST))
}

/// `GET /api/v3/core/tokens/{identifier}/`.
pub async fn retrieve(
    ctx: &Context<'_>,
    req: &ApiRequest<'_>,
    query: &QueryDict,
    identifier: &str,
) -> Result<Answer, Decline> {
    if identifier.contains('\0') {
        return Err(Decline("NUL in lookup"));
    }
    let tenant = drf::tenant(ctx, req).await?;
    let user = match drf::authenticate(ctx, req, ALLOW_DETAIL).await? {
        Ok(user) => user,
        Err(answer) => return Ok(answer),
    };
    let mut qs = match filter_queryset(ctx, query, &user, ALLOW_DETAIL).await? {
        Ok(qs) => qs,
        Err(answer) => return Ok(answer),
    };
    let p = qs.bind(Bind::Text(identifier.to_owned()));
    qs.filter(format!("{} = {p}", col!("identifier")));
    let rows = qs.fetch(ctx.pool, &[], None).await?;
    let row = match rows.as_slice() {
        [] => {
            return Ok(drf::detail(
                404,
                "No Token matches the given query.",
                ALLOW_DETAIL,
            ));
        }
        [row] => row,
        _ => return Err(Decline("multiple objects")),
    };
    let uuid: Uuid = row.try_get(3).map_err(db)?;
    let owner: i32 = row.try_get(7).map_err(db)?;
    let pk_text = uuid.to_string();
    let access = ak_rbac::has_object_permission(
        ctx.pool,
        user.subject(),
        "GET",
        &Object {
            model: MODEL,
            pk: &pk_text,
        },
        owner == user.subject().user_id,
    )
    .await
    .map_err(|_| Decline("object permission raised"))?;
    match access {
        Access::Allow => {
            let mut tokens = serialize_tokens(ctx, &tenant, query, &rows).await?;
            let one = tokens.pop().ok_or(Decline("database error"))?;
            Ok(drf::json(200, &one, ALLOW_DETAIL))
        }
        Access::NotFound => Ok(drf::detail(404, "Not found.", ALLOW_DETAIL)),
        Access::Deny => Ok(drf::permission_denied(&user, ALLOW_DETAIL)),
    }
}
