#!/usr/bin/env python3
"""Generate rust/crates/ak-api/src/registry.rs from the live app registry.

Input: baseline/inventory/verbose_names.json, extracted inside the 2026.2.7
reference (str(AppConfig.verbose_name) per label, str(Model._meta.verbose_name)
per "app_label.model_name", English). `apps.get_app_config` and
`apps.get_model` raise LookupError for anything not listed.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "baseline/inventory/verbose_names.json").read_text())


def table(name, items):
    rows = "\n".join(f"    ({json.dumps(k)}, {json.dumps(v)})," for k, v in sorted(items.items()))
    return f"pub(crate) const {name}: &[(&str, &str)] = &[\n{rows}\n];\n"


out = (
    "// @generated by scripts/gen_api_registry.py from baseline/inventory/verbose_names.json.\n"
    "//! Django's app registry as authentik 2026.2.7 builds it: `verbose_name`\n"
    "//! per app label and per `app_label.model_name`, sorted for binary search.\n\n"
    + table("APP_VERBOSE_NAMES", data["apps"])
    + "\n"
    + table("MODEL_VERBOSE_NAMES", data["models"])
    + """
fn find(table: &[(&str, &'static str)], key: &str) -> Option<&'static str> {
    table
        .binary_search_by(|(k, _)| (*k).cmp(key))
        .ok()
        .map(|i| table[i].1)
}

/// `apps.get_app_config(label).verbose_name`, `None` for `LookupError`.
pub(crate) fn app_verbose_name(label: &str) -> Option<&'static str> {
    find(APP_VERBOSE_NAMES, label)
}

/// `apps.get_model(app_label, model)._meta.verbose_name`.
pub(crate) fn model_verbose_name(app_label: &str, model: &str) -> Option<&'static str> {
    find(MODEL_VERBOSE_NAMES, &format!("{app_label}.{}", model.to_lowercase()))
}
"""
)
(ROOT / "rust/crates/ak-api/src/registry.rs").write_text(out)
print("wrote registry.rs")
