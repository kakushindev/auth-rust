#!/usr/bin/env python3
"""Generate docs/FEATURE_MATRIX.md from runtime inventory + hand-maintained status.

Inputs (all committed):
  baseline/inventory/django.json             live Django registry of the reference
  baseline/inventory/openapi_operations.json operations in the pinned OpenAPI schema
  baseline/inventory/go_components.json      Go outposts / server binaries (static scan)
  docs/feature-status.json                   status + evidence per feature id

Every feature defaults to "Not started". Only docs/feature-status.json can
raise a status, and anything above "Implemented, unverified" must cite evidence.
"""

import collections
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STATES = [
    "Not started",
    "In implementation",
    "Implemented, unverified",
    "Verified equivalent",
    "Blocked with documented evidence",
]


def load(rel):
    return json.loads((ROOT / rel).read_text())


def module_app(module, app_names):
    """Longest authentik app name that prefixes the module."""
    best = None
    for name in app_names:
        if module == name or module.startswith(name + "."):
            if best is None or len(name) > len(best):
                best = name
    return best


def main():
    django = load("baseline/inventory/django.json")
    go = load("baseline/inventory/go_components.json")
    status = load("docs/feature-status.json")

    apps = [c for c in django["app_configs"] if c["name"].startswith("authentik")]
    names = [a["name"] for a in apps]
    tenant_apps = set(django["tenant_apps"])

    models = collections.defaultdict(list)
    for m in django["models"]:
        app = module_app(m["module"], names)
        if app:
            models[app].append(m)
    routes = collections.defaultdict(list)
    for u in django["urls"]:
        app = module_app(u["view"], names)
        if app:
            routes[app].append(u)
    actors = collections.defaultdict(list)
    for a in django["actors"]:
        app = module_app(a["module"] or "", names)
        if app:
            actors[app].append(a)

    rows = []
    for app in sorted(apps, key=lambda a: a["name"]):
        fid = f"django:{app['name']}"
        rows.append(
            {
                "id": fid,
                "component": app["name"],
                "kind": "Django app (EE)" if ".enterprise" in app["name"] else "Django app",
                "scope": "tenant" if app["name"] in tenant_apps else "shared",
                "tables": sorted({m["db_table"] for m in models[app["name"]] if not m["proxy"]}),
                "routes": len(routes[app["name"]]),
                "actors": [a["actor"] for a in actors[app["name"]]],
            }
        )
    for comp in go["components"]:
        rows.append(
            {
                "id": f"go:{comp['name']}",
                "component": comp["name"],
                "kind": comp["kind"],
                "scope": "outpost" if comp["kind"].startswith("Go outpost") else "runtime",
                "tables": [],
                "routes": 0,
                "actors": [],
                "files": comp["files"],
            }
        )
    for extra in status.get("extra_features", []):
        rows.append(
            {
                "id": extra["id"],
                "component": extra["component"],
                "kind": extra["kind"],
                "scope": extra.get("scope", "cross-cutting"),
                "tables": [],
                "routes": 0,
                "actors": [],
            }
        )

    known = {r["id"] for r in rows}
    for fid, entry in status["features"].items():
        if fid not in known:
            sys.exit(f"feature-status.json references unknown feature {fid}")
        if entry["status"] not in STATES:
            sys.exit(f"{fid}: invalid status {entry['status']!r}")
        if STATES.index(entry["status"]) >= 3 and not entry.get("evidence"):
            sys.exit(f"{fid}: status {entry['status']!r} requires evidence")

    counts = collections.Counter()
    out = [
        "# Feature matrix",
        "",
        "Generated by `scripts/gen_feature_matrix.py`. Do not edit by hand: change",
        "`docs/feature-status.json` and regenerate. Rows come from the live Django",
        "app registry of the pinned reference (authentik 2026.8.5,",
        "`4ec0d19b98da3c329781894cd550da95d3033954`) plus a static scan of the Go tree.",
        "",
        "Only **Verified equivalent** counts as complete.",
        "",
    ]
    table = [
        "| Feature | Kind | Scope | Tables | URL routes | Background actors | Rust replacement | Status | Evidence |",
        "| --- | --- | --- | ---: | ---: | --- | --- | --- | --- |",
    ]
    for r in rows:
        entry = status["features"].get(r["id"], {})
        st = entry.get("status", "Not started")
        counts[st] += 1
        table.append(
            "| `{}` | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                r["component"],
                r["kind"],
                r["scope"],
                len(r["tables"]),
                r["routes"],
                ", ".join(f"`{a}`" for a in r["actors"]) or "—",
                entry.get("rust", "—"),
                st,
                entry.get("evidence", "—"),
            )
        )
    total = sum(counts.values())
    out.append("## Summary")
    out.append("")
    out.append("| Status | Features |")
    out.append("| --- | ---: |")
    for st in STATES:
        out.append(f"| {st} | {counts[st]} |")
    out.append(f"| **Total** | **{total}** |")
    out.append("")
    out.append(
        f"Verified equivalent: {counts['Verified equivalent']}/{total} "
        f"({100 * counts['Verified equivalent'] / total:.1f}%)."
    )
    out.append("")
    out.append("## Features")
    out.append("")
    out.extend(table)
    out.append("")
    out.append("## Tables per Django app")
    out.append("")
    for r in rows:
        if r["tables"]:
            out.append(f"- `{r['component']}`: " + ", ".join(f"`{t}`" for t in r["tables"]))
    out.append("")
    (ROOT / "docs/FEATURE_MATRIX.md").write_text("\n".join(out))
    print(f"wrote docs/FEATURE_MATRIX.md: {total} features, {dict(counts)}")


if __name__ == "__main__":
    main()
